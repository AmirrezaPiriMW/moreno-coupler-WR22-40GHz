"""Regenerate the results block of README.md from docs/report/key_numbers.json.

    python docs/report/update_readme.py      (build_report.py writes key_numbers.json)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
k = json.loads((ROOT / "docs" / "report" / "key_numbers.json").read_text())
s = k["reference_summary"]
chart = "\n".join("| %.1f mm | %.1f dB |" % (c["L_mm"], c["C_corrected"]) for c in k["chart"])
levels = ", ".join("**%g dB → L = %.2f mm**" % (C, L) for C, L in k["targets"] if L is not None)
block = f"""<!-- results:start (generated by docs/report/update_readme.py) -->
### Simulated performance at 40 GHz (openEMS, lossless walls)

| Coupling S31 | Directivity | Isolation S41 | Return loss | Through loss |
|---|---|---|---|---|
| **{k['coupling_extrapolated_db']:.2f} ± {k['coupling_uncertainty_db']:.2f} dB** | **{k['directivity_converged_db']:.1f} ± {k['directivity_uncertainty_db']:.1f} dB** | {s['isolation_db_at_f0']:.1f} dB | {s['return_loss_db_at_f0']:.1f} dB | {s['insertion_loss_db_at_f0']:.3f} dB |

Coupling and directivity are bracketed by two mesh-refinement series that converge
from opposite sides (the coupling uncertainty also includes the other numerical
parameters); isolation, return loss and through loss are from the finest mesh
(slot cell {k['finest_slot_cell_mm']} mm), and the return loss is a lower bound. Directivity stays above
30 dB from {k['directivity_above_30_ghz'][0]:.1f} to {k['directivity_above_30_ghz'][1]:.1f} GHz. The model passes power-balance
({k['power_balance_full'][0]:.4f}–{k['power_balance_full'][1]:.4f}) and reciprocity ({k['reciprocity']:.1e}) checks.
Details: [technical report (PDF)](docs/report/Moreno_Coupler_WR22_40GHz_Report.pdf).

![openEMS S-parameters](docs/report/figures/fig_sparams.png)

**Choosing the coupling level** (slot arm length L, mesh-corrected, 40 GHz): {levels}.

| L | Coupling |
|---|---|
{chart}

Sensitivity of the coupling per 0.01 mm: slot length {k['dC_dL_db_per_0.01mm']:+.2f} dB, slot width
{k['dC_dw_db_per_0.01mm']:+.2f} dB, wall thickness {k['dC_dt_db_per_0.01mm']:+.2f} dB (negative = stronger coupling).
Copper loss of the feeds: {k['copper_loss_db_per_m']:.2f} dB/m at 40 GHz.
<!-- results:end -->"""
readme = (ROOT / "README.md").read_text()
new = re.sub(r"<!-- results:start.*?<!-- results:end -->", block, readme, flags=re.S)
(ROOT / "README.md").write_text(new)
print("README results block updated" if new != readme else "README unchanged")
